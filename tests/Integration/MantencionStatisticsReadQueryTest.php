    public function test_get_entrypoint_uses_resolved_filters_and_empty_results_do_not_read_details(): void
    {
        $get = $_GET;
        $post = $_POST;
        try {
            $_POST = [];
            $_GET = ['desde' => '2026-09-03', 'hasta' => '2026-09-01', 'usuario' => '101'];
            $service = new MantencionEstadisticasService;
            $filters = $service->resolveFilters([], $_GET);
            self::assertSame($this->comparable($this->reference($filters)), $this->comparable($service->handle()));
        } finally {
            $_GET = $get;
            $_POST = $post;
        }
        DB::flushQueryLog();
        DB::enableQueryLog();
        $actual = (new MantencionEstadisticasService)->statisticsForFilters(['usuario' => 'missing']);
        $queries = DB::getQueryLog();
        DB::disableQueryLog();
        self::assertSame(0, $actual['total']);
        $reads = array_filter($queries, fn ($q) => str_contains($q['query'], 'from `redmine_mantencion_reportes`'));
        self::assertCount(3, $reads);
        foreach ($reads as $query) {
            self::assertStringNotContainsString('`r`.*', $query['query']);
            self::assertStringNotContainsString('descripcion', $query['query']);
            self::assertStringNotContainsString('asunto', $query['query']);
        }
    }

