    public function test_filtered_statistics_fall_back_when_the_detail_read_fails(): void
    {
        $filters = ['desde' => '2026-09-01', 'hasta' => '2026-09-03'];
        $expected = $this->comparable($this->reference($filters));
        self::assertGreaterThan(0, $expected['total']);

        $dispatcher = new Dispatcher(app());
        DB::connection()->setEventDispatcher($dispatcher);
        $failed = false;
        $dispatcher->listen(QueryExecuted::class, function (QueryExecuted $event) use (&$failed): void {
            if (! $failed && str_contains($event->sql, '`redmine_mantencion_reportes`')
                && str_contains($event->sql, '`r`.*') && str_contains($event->sql, 'id IN (')) {
                $failed = true;
                throw new \RuntimeException('Synthetic statistics detail read failure');
            }
        });
        try {
            self::assertSame($expected, $this->comparable((new MantencionEstadisticasService)->statisticsForFilters($filters)));
            self::assertTrue($failed);
        } finally {
            DB::connection()->unsetEventDispatcher();
        }
    }

    public function test_large_reports_outside_the_range_do_not_transfer_their_text(): void
    {
        $seed = (array) DB::table('redmine_mantencion_reportes')->where('id', 7)->first();
        for ($batch = 0; $batch < 4; $batch++) {
            $reports = $links = [];
            for ($i = 1; $i <= 100; $i++) {
                $id = 1000 + $batch * 100 + $i;
                $reports[] = array_replace($seed, ['id' => $id, 'fuente' => 'manual', 'fuente_id' => 'large-'.$id,
                    'estado' => $i % 2 ? 'archivado' : 'pendiente', 'fecha_reporte' => '2023-01-01',
                    'asunto' => str_repeat('Asunto ', 1000), 'descripcion' => str_repeat('Detalle largo. ', 3000)]);
                foreach ([1, 2, 3] as $group) {
                    $links[] = ['grupo_id' => $group, 'origen' => 'mantencion', 'reporte_id' => $id];
                }
            }
            DB::table('redmine_mantencion_reportes')->insert($reports);
            DB::table('horas_extra_grupo_reportes')->insert($links);
        }
        unset($reports, $links, $seed);
        $filter = ['desde' => '2026-09-01', 'hasta' => '2026-09-03'];
        $measure = function (callable $read): array {
            gc_collect_cycles();
            memory_reset_peak_usage();
            $memory = memory_get_usage();
            $start = hrtime(true);
            $value = $read();

            return [$value, ['elapsed_ms' => round((hrtime(true) - $start) / 1e6, 3), 'peak_bytes' => memory_get_peak_usage() - $memory]];
        };
        $this->reference($filter);
        (new MantencionEstadisticasService)->statisticsForFilters($filter);
        [$expected, $before] = $measure(fn () => $this->reference($filter));
        [$actual, $after] = $measure(fn () => (new MantencionEstadisticasService)->statisticsForFilters($filter));
        self::assertSame($this->comparable($expected), $this->comparable($actual));
        self::assertLessThan($before['peak_bytes'] / 4, $after['peak_bytes']);
        file_put_contents(sys_get_temp_dir().'/nova-p06-mantencion-statistics-metrics.json', json_encode(compact('before', 'after')), LOCK_EX);
    }

    public function test_concurrent_changes_do_not_mix_metadata_and_details_in_the_read_transaction(): void
    {
        $filters = ['desde' => '2020-01-01'];
        $expected = $this->comparable($this->reference($filters));
        $dispatcher = new Dispatcher;
        DB::connection()->setEventDispatcher($dispatcher);
        $changed = false;
        $dispatcher->listen(QueryExecuted::class, function ($event) use (&$changed): void {
            if (! $changed && str_starts_with($event->sql, 'select `r`.`id`, `r`.`fuente`')) {
                $changed = true;
                DB::connection('concurrent')->table('redmine_mantencion_reportes')->where('id', 7)->update([
                    'descripcion' => 'Cambio concurrente', 'id_redmine_asignado' => 'new-owner', 'asignado_nombre' => 'Nueva persona',
                ]);
            }
        });
        try {
            self::assertSame($expected, $this->comparable((new MantencionEstadisticasService)->statisticsForFilters($filters)));
            self::assertTrue($changed);
        } finally {
            DB::connection()->unsetEventDispatcher();
        }
        self::assertSame($this->comparable($this->reference($filters)), $this->comparable((new MantencionEstadisticasService)->statisticsForFilters($filters)));
    }
