    private function reference(array $filters): array
    {
        $read = require __DIR__.'/fixtures/mantencion_statistics_reference.php';

        return $read->call(new MantencionEstadisticasService, $filters);
    }

    private function comparable(array $stats): array
    {
        // Wall-clock refresh label is generated by both readers, independently.
        unset($stats['actualizado']);

        return $stats;
    }

    public function test_three_sources_preserve_filters_repetition_order_and_all_message_fields(): void
    {
        $service = new MantencionEstadisticasService;
        $filters = [[], ['desde' => '2026-09-02'], ['hasta' => '2026-09-02'],
            ['desde' => '2026-09-03', 'hasta' => '2026-09-01'], ['desde' => 'invalid'],
            ['desde' => '2030-01-01'], ['categoria' => 'red'], ['categoria' => 'réd'],
            ['categoria' => 'ELÉCTRICA'], ['categoria' => 'eléctrica'], ['categoria' => 'Modificar Perfil CORE'],
            ['categoria' => '0'], ['unidad' => 'Red'], ['unidad' => 'N/A'], ['unidad' => '0'],
            ['usuario' => '101'], ['usuario' => '0101'], ['usuario' => '202'], ['usuario' => 'Pérez'],
            ['usuario' => 'PÃ©rez'], ['usuario' => '0'], ['usuario' => 'missing'],
            ['desde' => '2026-09-01', 'hasta' => '2026-09-03', 'usuario' => '101', 'categoria' => 'Red']];
        foreach ($filters as $filter) {
            self::assertSame($this->comparable($this->reference($filter)), $this->comparable($service->statisticsForFilters($filter)));
        }
        $rows = array_merge(...array_values($service->statisticsForFilters([])['msgs_por_usuario']));
        $sources = array_count_values(array_column($rows, '_fuente'));
        self::assertGreaterThan(0, $sources['mensajes']);
        self::assertGreaterThan(0, $sources['reportes']);
        self::assertGreaterThan(0, $sources['horas_extra']);
        $foreign = array_values(array_filter($rows, fn ($r) => $r['id'] === 'message-13'));
        self::assertCount(3, $foreign, 'The existing hours reader includes linked archived rows without a module predicate.');
        self::assertSame(['horas_extra'], array_values(array_unique(array_column($foreign, '_fuente'))));
        self::assertGreaterThan(count(array_unique(array_column($rows, 'id'))), count($rows), 'Repeated source/hour contributions are intentionally retained.');
        self::assertCount(0, array_filter($rows, fn ($r) => array_key_exists('_statistics_id', $r)));
        foreach ($rows as $row) {
            self::assertArrayHasKey('descripcion', $row);
            self::assertArrayHasKey('numero_ticket_redmine', $row);
        }
    }

